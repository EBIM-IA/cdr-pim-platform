import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react';
import { createDefaultPdfDesignConfig } from '@cdr/contracts';
import type * as PdfDesignTools from '@/lib/pdf-designs';
import { PdfDesignWorkspace } from './pdf-design-workspace';

const mocks = vi.hoisted(() => ({
  load: vi.fn(),
  save: vi.fn(),
  templates: vi.fn(),
  template: vi.fn(),
  brands: vi.fn(),
  saveBrand: vi.fn(),
  workbook: vi.fn(),
  sheet: vi.fn(),
  assets: vi.fn(),
  render: vi.fn(),
  download: vi.fn(),
  downloadCsv: vi.fn(),
}));
vi.mock('@/lib/pdf-design-api', () => ({
  fetchPdfDesignSettings: mocks.load,
  savePdfDesignSettings: mocks.save,
}));
vi.mock('@/lib/catalog-admin-api', () => ({
  listAdminTemplates: mocks.templates,
  getAdminTemplate: mocks.template,
}));
vi.mock('@/lib/catalog-parameters-api', () => ({
  listCatalogParameters: mocks.brands,
  saveCatalogParameter: mocks.saveBrand,
}));
vi.mock('@/lib/dynamic-catalog-api', () => ({
  fetchCatalogWorkbook: mocks.workbook,
  fetchProductTechnicalSheet: mocks.sheet,
}));
vi.mock('@/lib/product-assets-api', () => ({ listProductAssets: mocks.assets }));
vi.mock('@/lib/technical-sheet-pdf', () => ({ createTechnicalSheetPdf: mocks.render }));
vi.mock('@/lib/tabular-export', () => ({ downloadCsv: mocks.downloadCsv }));
vi.mock('@/lib/zip-export', () => ({
  downloadBinary: mocks.download,
  technicalSheetFilename: (sku: string) => `${sku}.pdf`,
}));
vi.mock('@/lib/technical-sheet-export', () => ({
  technicalSheetDocument: () => ({ sku: 'REAL-1200', name: 'Producto real', attributes: [] }),
  technicalSheetDesign: (_: unknown, config: ReturnType<typeof createDefaultPdfDesignConfig>) => ({
    design: config.designs[0],
  }),
  technicalSheetLogo: async () => new Uint8Array(),
  technicalSheetMedia: async () => [],
  technicalSheetBrand: async () => ({}),
  technicalSheetCopy: async () => ({}),
}));
vi.mock('@/components/pdf-document-pages', () => ({
  PdfDocumentPages: ({ bytes }: { bytes: Uint8Array | null }) => (
    <div>{bytes ? 'PDF real listo' : 'Preparando PDF'}</div>
  ),
}));
vi.mock('@/lib/pdf-designs', async (original) => ({
  ...(await original<typeof PdfDesignTools>()),
  pdfImageDataUrl: async () => 'data:image/png;base64,aW1hZ2U=',
}));
afterEach(cleanup);
const initial = () => ({
  config: createDefaultPdfDesignConfig(),
  updatedAt: '2026-11-20T10:00:00.000Z',
});
beforeEach(() => {
  vi.clearAllMocks();
  mocks.load.mockResolvedValue(initial());
  mocks.save.mockImplementation(async (input) => ({
    ...input,
    updatedAt: '2026-11-20T10:00:01.000Z',
  }));
  mocks.templates.mockResolvedValue([
    {
      id: 'template-real',
      name: 'Plantilla real',
      sections: [{ key: 'car', label: 'Características', position: 0 }],
    },
  ]);
  mocks.template.mockResolvedValue({
    id: 'template-real',
    name: 'Plantilla real',
    sections: [{ key: 'car', label: 'Características', position: 0 }],
    attributes: [
      { sectionKey: 'car', active: true, includeInTechnicalSheet: true },
      { sectionKey: 'car', active: true, includeInTechnicalSheet: false },
    ],
  });
  mocks.brands.mockResolvedValue([
    {
      id: 'brand-real',
      value: 'SKF',
      kind: 'brand',
      description: 'Datos de marca',
      target: null,
      active: true,
      version: 3,
      logoDataUrl: null,
    },
  ]);
  mocks.workbook.mockResolvedValue({
    items: [{ id: 'product-real', sku: 'REAL-1200', name: 'Producto real', brand: 'SKF' }],
    facets: { brands: ['SKF'] },
  });
  mocks.sheet.mockResolvedValue({
    product: { id: 'product-real', sku: 'REAL-1200', brand: 'SKF' },
    schema: {
      columns: [],
      template: { id: 'template-real', name: 'Plantilla real' },
      sections: [{ key: 'car', label: 'Características', position: 0 }],
    },
  });
  mocks.assets.mockResolvedValue([]);
  mocks.render.mockResolvedValue(new Uint8Array([37, 80, 68, 70]));
  mocks.saveBrand.mockImplementation(async (input) => ({
    ...input,
    id: input.id ?? 'new-brand',
    version: input.expectedVersion + 1,
  }));
});
describe('PDF design workspace', () => {
  it('previews a real SKU and downloads the same generated bytes', async () => {
    render(<PdfDesignWorkspace canManage />);
    await screen.findByText('PDF real listo');
    expect(mocks.assets).toHaveBeenCalledWith(
      { productId: 'product-real' },
      expect.any(AbortSignal),
    );
    fireEvent.click(screen.getByRole('button', { name: 'Descargar muestra' }));
    expect(mocks.download).toHaveBeenCalledWith(
      new Uint8Array([37, 80, 68, 70]),
      'REAL-1200.pdf',
      'application/pdf',
    );
  });
  it('disables download immediately when the selected design starts regenerating', async () => {
    render(<PdfDesignWorkspace canManage />);
    await screen.findByText('PDF real listo');
    mocks.render.mockImplementation(() => new Promise<Uint8Array>(() => undefined));
    fireEvent.change(screen.getByRole('combobox', { name: 'Diseño en edición' }), {
      target: { value: 'compacta' },
    });
    expect(screen.getByRole('button', { name: 'Descargar muestra' })).toBeDisabled();
    expect(mocks.download).not.toHaveBeenCalled();
  });
  it('shows exportable counts and switches the real sample when a template is selected', async () => {
    mocks.templates.mockResolvedValue([
      {
        id: 'template-real',
        categoryId: 'category-one',
        name: 'Plantilla real',
        sections: [{ key: 'car', label: 'Características', position: 0 }],
      },
      { id: 'template-two', categoryId: 'category-two', name: 'Otra plantilla', sections: [] },
    ]);
    render(<PdfDesignWorkspace canManage />);
    await screen.findByText('1 exportables de 2');
    await screen.findByText('PDF real listo');
    mocks.workbook.mockResolvedValueOnce({
      items: [
        {
          id: 'product-two',
          sku: 'REAL-2200',
          name: 'Segundo producto',
          brand: 'SKF',
          template: { id: 'template-two' },
        },
      ],
      total: 1,
    });
    mocks.sheet.mockResolvedValue({
      product: { id: 'product-two', sku: 'REAL-2200', brand: 'SKF' },
      schema: {
        columns: [],
        template: { id: 'template-two', name: 'Otra plantilla' },
        sections: [],
      },
    });
    fireEvent.change(screen.getByRole('combobox', { name: 'Plantilla' }), {
      target: { value: 'template-two' },
    });
    await waitFor(() =>
      expect(mocks.assets).toHaveBeenCalledWith(
        { productId: 'product-two' },
        expect.any(AbortSignal),
      ),
    );
    expect(mocks.workbook).toHaveBeenCalledWith(
      expect.objectContaining({ categoryId: 'category-two' }),
      expect.any(AbortSignal),
    );
  });
  it('saves changed design options with the concurrency timestamp and preserves failed edits', async () => {
    render(<PdfDesignWorkspace canManage />);
    const name = await screen.findByLabelText('Nombre');
    fireEvent.change(name, { target: { value: 'Formato aprobado' } });
    await waitFor(
      () =>
        expect(mocks.save).toHaveBeenCalledWith(
          expect.objectContaining({
            updatedAt: '2026-11-20T10:00:00.000Z',
            config: expect.objectContaining({
              designs: expect.arrayContaining([
                expect.objectContaining({ name: 'Formato aprobado' }),
              ]),
            }),
          }),
        ),
      { timeout: 2500 },
    );
    mocks.save.mockRejectedValueOnce(new Error('La configuración cambió en otra sesión.'));
    fireEvent.change(name, { target: { value: 'Mi cambio pendiente' } });
    await screen.findByText('La configuración cambió en otra sesión.', {}, { timeout: 2500 });
    expect(name).toHaveValue('Mi cambio pendiente');
  });
  it('stores uploaded brand logos in the canonical catalog with the existing version', async () => {
    render(<PdfDesignWorkspace canManage />);
    const input = await screen.findByLabelText('Logotipo de SKF');
    fireEvent.change(input, {
      target: { files: [new File(['image'], 'SKF.png', { type: 'image/png' })] },
    });
    await waitFor(() =>
      expect(mocks.saveBrand).toHaveBeenCalledWith(
        expect.objectContaining({
          id: 'brand-real',
          expectedVersion: 3,
          logoDataUrl: 'data:image/png;base64,aW1hZ2U=',
          description: 'Datos de marca',
        }),
      ),
    );
    expect(mocks.save).not.toHaveBeenCalled();
  });
  it('exports names accepted by bulk upload, including brands outside the preview page', async () => {
    mocks.workbook.mockResolvedValue({
      items: [{ id: 'product-real', sku: 'REAL-1200', name: 'Producto real', brand: 'SKF' }],
      facets: { brands: ['SKF', 'Águila/EC', 'Marca "Especial"', 'A/B', 'A B'] },
    });
    render(<PdfDesignWorkspace canManage />);
    const download = await screen.findByRole('button', { name: 'Lista de marcas (CSV)' });
    await waitFor(() => expect(download).toBeEnabled());
    fireEvent.change(screen.getByRole('combobox', { name: 'Mostrar' }), {
      target: { value: 'none' },
    });
    fireEvent.click(download);

    expect(mocks.downloadCsv).toHaveBeenCalledWith(
      {
        headers: ['Marca', 'Archivo sugerido'],
        rows: [
          ['A B', 'A B.png'],
          ['A/B', null],
          ['Águila/EC', 'Águila EC.png'],
          ['Marca "Especial"', 'Marca Especial.png'],
          ['SCHAEFFLER', 'SCHAEFFLER.png'],
          ['SKF', 'SKF.png'],
        ],
      },
      'marcas_logotipos',
    );
  });
  it('exports registered brands with an availability notice if the product catalog fails', async () => {
    mocks.workbook.mockRejectedValue(new Error('Productos indisponibles'));
    render(<PdfDesignWorkspace canManage />);
    await screen.findByText(/La consulta de marcas de los SKU está temporalmente indisponible/);
    fireEvent.click(screen.getByRole('button', { name: 'Lista de marcas (CSV)' }));
    expect(mocks.downloadCsv).toHaveBeenCalledWith(
      {
        headers: ['Marca', 'Archivo sugerido'],
        rows: [
          ['SCHAEFFLER', 'SCHAEFFLER.png'],
          ['SKF', 'SKF.png'],
        ],
      },
      'marcas_logotipos',
    );
  });
  it('keeps consultation read only while allowing a real preview download', async () => {
    render(<PdfDesignWorkspace canManage={false} />);
    expect(await screen.findByLabelText('Nombre')).toBeDisabled();
    expect(screen.queryByRole('button', { name: 'Duplicar' })).not.toBeInTheDocument();
    expect(screen.queryByRole('button', { name: 'Lista de marcas (CSV)' })).not.toBeInTheDocument();
    await screen.findByText('PDF real listo');
    expect(screen.getByRole('button', { name: 'Descargar muestra' })).toBeEnabled();
    expect(mocks.save).not.toHaveBeenCalled();
  });
});
